"""Write requirements.lock for the platform this runs on (run inside the pinned base image, see build_cpu_image.sh).

Downloads only the wheels pip would install here (linux/aarch64 or x86_64, CPython 3.10), checks that they install
together offline, and pins each one with its exact version and SHA-256. pip-compile --generate-hashes would instead
download every platform's wheel of every pin (hundreds of MB per torch build) just to hash it.
"""
import hashlib
import platform
import re
import subprocess
import sys
from pathlib import Path

WHEELS = Path("/tmp/wheels")
src = Path("requirements.in")
pip = [sys.executable, "-m", "pip", "--disable-pip-version-check", "-q"]
subprocess.run(pip + ["download", "--only-binary=:all:", "-d", str(WHEELS), "-r", str(src)], check=True)
subprocess.run([sys.executable, "-m", "venv", "/tmp/venv"], check=True)
subprocess.run(["/tmp/venv/bin/pip", "-q", "install", "--no-index", "--find-links", str(WHEELS), "-r", str(src)],
               check=True)
frozen = subprocess.run(["/tmp/venv/bin/pip", "freeze", "--all"], check=True, capture_output=True, text=True).stdout

norm = lambda s: re.sub(r"[-_.]+", "-", s).lower()  # noqa: E731
files = {}
for whl in WHEELS.glob("*.whl"):
    name, ver = whl.name.split("-")[:2]
    files[(norm(name), ver.replace("%2B", "+"))] = whl
lines = [f"# Generated by tools/docker/make_lock.py for {platform.machine()} / CPython {platform.python_version()}.",
         "# Do not edit; change requirements.in and run tools/build_cpu_image.sh --lock.",
         "--extra-index-url https://download.pytorch.org/whl/cpu"]
for line in sorted(frozen.splitlines(), key=str.lower):
    name, ver = line.split("==")
    if norm(name) in ("pip", "setuptools", "wheel"):
        continue
    whl = files[(norm(name), ver)]
    digest = hashlib.sha256(whl.read_bytes()).hexdigest()
    lines.append(f"{name}=={ver} --hash=sha256:{digest}")
Path("requirements.lock").write_text("\n".join(lines) + "\n")
print(f"requirements.lock: {len(lines) - 3} packages")
